// Builds the committed asset files from catalog data. Pure: returns file contents, writes nothing.
import type { CatalogEntry, PCCatalog } from "@ytl/contracts";
import { gpuGeometry } from "./gpu";
import { motherboardGeometry } from "./motherboard";
import { cableGeometry, caseGeometry, coolingGeometry, cpuGeometry, fanGeometry, monitorGeometry, psuGeometry, ramGeometry, storageGeometry } from "./parts";
import { renderThumbnail, type View } from "./svg";
import { EDUCATIONAL_LABEL, GEOMETRY_SCHEMA, MANIFEST_PATH, geometryPath, thumbnailPath, type AssetManifest, type AssetManifestRow, type PartGeometry } from "./types";

export const GENERATOR_VERSION = "pc-visual-3";
export const PROVENANCE = "Original procedural educational geometry generated by Your Tech Lab from catalog data.";
export const LICENSE = "Original work created for the Your Tech Lab project. Licence to be set by the project owner.";

/** Geometry for one catalog entry. */
export function partGeometry(entry: CatalogEntry, catalogVersion: string): PartGeometry {
  switch (entry.category) {
    case "case": return caseGeometry(entry, catalogVersion);
    case "motherboard": return motherboardGeometry(entry, catalogVersion);
    case "cpu": return cpuGeometry(entry, catalogVersion);
    case "ram": return ramGeometry(entry, catalogVersion);
    case "gpu": return gpuGeometry(entry, catalogVersion);
    case "psu": return psuGeometry(entry, catalogVersion);
    case "storage": return storageGeometry(entry, catalogVersion);
    case "fan": return fanGeometry(entry, catalogVersion);
    case "cooling": return coolingGeometry(entry, catalogVersion);
    case "cable": return cableGeometry(entry, catalogVersion);
    case "monitor": return monitorGeometry(entry, catalogVersion);
  }
}

/** Views drawn side by side; the first is the main one. */
const VIEWS: Record<CatalogEntry["category"], View[]> = {
  case: ["front"], // the open side: tray, shroud, drive bays, and the fan positions along the walls
  motherboard: ["top", "back"],
  cpu: ["top"],
  ram: ["front"],
  gpu: ["front", "back", "top"],
  psu: ["front", "back", "top"],
  storage: ["top", "back"],
  fan: ["front"],
  cooling: ["front", "back"], // from the side, and facing the fan
  cable: ["top"],
  monitor: ["front"],
};

export interface GeneratedAssets {
  /** Path under `assets/` -> file content. */
  files: Record<string, string>;
  manifest: AssetManifest;
}

/** Generates assets for the listed entries (default: every entry that has a generator). */
export function generateAssets(catalog: PCCatalog, only?: readonly string[]): GeneratedAssets {
  const files: Record<string, string> = {};
  const assets: AssetManifestRow[] = [];
  for (const entry of catalog.entries) {
    if (only && !only.includes(entry.id)) continue;
    const geometry = partGeometry(entry, catalog.version);
    files[geometryPath(entry.id)] = `${JSON.stringify(geometry, null, 2)}\n`;
    files[thumbnailPath(entry.id)] = renderThumbnail(geometry, VIEWS[entry.category], `${entry.brand} ${entry.model}`);
    assets.push({
      catalogId: entry.id,
      catalogVersion: catalog.version,
      geometry: geometryPath(entry.id),
      thumbnail: thumbnailPath(entry.id),
      generator: GENERATOR_VERSION,
      provenance: PROVENANCE,
      license: LICENSE,
      label: EDUCATIONAL_LABEL,
      orientation: { up: "+y", front: "+z" },
      metresPerUnit: 0.001,
    });
  }
  const manifest: AssetManifest = { schema: GEOMETRY_SCHEMA, assets };
  files[MANIFEST_PATH] = `${JSON.stringify(manifest, null, 2)}\n`;
  return { files, manifest };
}
