// Still placeholders: the three loose cables and the monitor (plug shapes are not specific to the connector,
// and the monitor's inputs are not shown). They are accessories and are not counted toward the catalog target.

export function assetFor(catalogId: string): AssetRef {
  const quality: AssetQuality = EDUCATIONAL.has(catalogId) ? "educational" : "placeholder";
  return {
    model: `pc/geometry/${catalogId}.json`,
    thumbnail: `pc/thumbnails/${catalogId}.svg`,
    kind: "procedural",
    provenance: "Original procedural educational geometry generated by Your Tech Lab from catalog data. Educational model — not manufacturer-accurate.",
    license: "Original work created for the Your Tech Lab project. Licence to be set by the project owner.",
    orientation: { up: "+y", front: "+z" },
    metresPerUnit: 0.001,
    quality,
  };
}
